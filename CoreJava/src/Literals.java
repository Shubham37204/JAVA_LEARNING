void main() {
//Literals
    //A variable is a named memory location used to store data,
    // while a literal is the fixed constant value written
    // directly in the program, such as 10, 'A', "Hello", or true.
    int num1=0b101;
    System.out.println(num1);
    float num4=56;
    System.out.println(num4);
    double num5=56;
    System.out.println(num5);
    double num6=12e10;
    System.out.println(num6);
}